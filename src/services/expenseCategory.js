// מנרמל להשוואה: אותיות קטנות, גרשיים אחידים, רווחים מכווצים.
function normalize(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/["'׳״]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * מציע קטגוריה לפי התיאור ובית העסק.
 * מחזיר תמיד קטגוריה תקפה — "אחר" כשאין התאמה.
 */
function suggestCategory(description, merchant) {
  const haystack = normalize(description) + " " + normalize(merchant);
  if (!haystack.trim()) return OTHER;

  for (const rule of RULES) {
    if (rule.words.some((w) => haystack.includes(normalize(w)))) return rule.category;
  }
  return OTHER;
}

// קטגוריה שהגיעה מהלקוח תקפה רק אם היא ברשימה; אחרת נופלים ל"אחר".
// מונע שמירת ערכים שרירותיים שישברו את דוח הפילוח.
function normalizeCategory(category) {
  return CATEGORIES.includes(category) ? category : OTHER;
}

